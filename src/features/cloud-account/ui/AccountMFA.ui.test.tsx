test('手工密钥默认折叠，复制保留原始内容并就地反馈，不提前确认绑定', async () => {
  const descriptor = Object.getOwnPropertyDescriptor(navigator, 'clipboard')
  const writeText = vi.fn(async () => undefined)
  Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText } })
  try {
    const { api } = gateway()
    render(security(api))
    await screen.findByText('未开启')
    fireEvent.click(screen.getByRole('button', { name: '开启二步验证' }))
    const dialog = within(await screen.findByRole('dialog'))
    fireEvent.change(dialog.getByLabelText('密码'), { target: { value: 'synthetic-password' } })
    fireEvent.click(dialog.getByRole('button', { name: '下一步' }))
    const summary = await dialog.findByText('无法扫码？手工输入密钥')
    expect(summary.closest('details')).not.toHaveAttribute('open')
    fireEvent.click(summary)
    fireEvent.click(dialog.getByRole('button', { name: '复制密钥' }))
    await dialog.findByRole('button', { name: '已复制' })
    expect(writeText).toHaveBeenCalledExactlyOnceWith(setup.secret)
    expect(api.mfaConfirm).not.toHaveBeenCalled()
    expect(dialog.getByLabelText('验证器验证码')).toHaveValue('')
  } finally {
    if (descriptor) Object.defineProperty(navigator, 'clipboard', descriptor)
    else Reflect.deleteProperty(navigator, 'clipboard')
  }
})

